-- Platform messaging tables. Each service owns these in its OWN database: the outbox is
-- per-service data, not shared state. Kept byte-identical across services so the entity
-- mappings in common-messaging validate everywhere.

CREATE TABLE outbox (
    id            VARCHAR(36) PRIMARY KEY,
    event_id      VARCHAR(36) NOT NULL UNIQUE,
    event_type    VARCHAR(80) NOT NULL,
    envelope_json TEXT NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at  TIMESTAMP WITH TIME ZONE,
    attempts      INTEGER NOT NULL,
    last_error    VARCHAR(500)
);

CREATE INDEX ix_outbox_unpublished ON outbox (published_at);

CREATE TABLE processed_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer     VARCHAR(80) NOT NULL,
    event_id     VARCHAR(36) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_processed_event_consumer_event UNIQUE (consumer, event_id)
);
